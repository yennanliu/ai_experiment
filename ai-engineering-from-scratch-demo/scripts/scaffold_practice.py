#!/usr/bin/env python3
"""Generate `practice.yaml` + solution stubs from a lesson's own exercise list.

Parses `## Exercises` from `docs/en.md` and `## 練習` from `docs/zh.md`, folds
wrapped lines back together, and emits the manifest with the text **verbatim and
bilingual** (D12) plus one stub per exercise with the docstring pre-filled.

`kind`, `tier` and `deps_group` are proposed by the same keyword classifier
`census.py` uses, so §5's estimates and the scaffold never disagree; a human
confirms them per phase batch (`DESIGN §6.4`).
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

from harness import coverage, parity  # noqa: E402

DEMOS = pathlib.Path(__file__).resolve().parent.parent / "demos" / "phases"

PROSE = re.compile(r"\b(explain|describe|discuss|why|what does|in your own words|"
                   r"write (?:a )?(?:short )?(?:paragraph|note)|argue|compare and contrast)\b", re.I)
GPU = re.compile(r"\b(gpu|cuda|vllm|fine-?tune|train (?:a|the) (?:model|network)|billion)\b", re.I)
API = re.compile(r"\b(api|openai|gpt-|claude|prompt the model|llm call)\b", re.I)
HEAVY = re.compile(r"\b(torch|pytorch|transformer|checkpoint|hugging ?face|embedding model)\b", re.I)
NUMERIC = re.compile(r"\b(numpy|matrix|eigen|svd|gradient|distribution|sample|fft|"
                     r"probability|variance|norm)\b", re.I)

STOPWORDS = {"a", "an", "the", "of", "to", "for", "in", "on", "and", "or", "that",
             "with", "your", "you", "it", "its", "is", "are", "be", "then", "using",
             "use", "given", "each", "every", "from", "at", "by", "as", "into"}


def classify(text: str):
    """(kind, tier, deps_group) — a proposal, not a verdict."""
    if PROSE.search(text) and not re.search(r"\b(implement|write|create|build|compute|plot)\b", text, re.I):
        return "explain", "T0", "none"
    if GPU.search(text):
        return "code", "T3", "llm"
    if API.search(text):
        return "code", "T2", "llm"
    if HEAVY.search(text):
        return "code", "T1", "llm"
    if NUMERIC.search(text):
        return "code", "T0", "math"
    return "code", "T0", "none"


def slug(text: str, used) -> str:
    words = re.findall(r"[a-z0-9]+", text.lower())
    keep = [w for w in words if w not in STOPWORDS][:4] or ["exercise"]
    base = "_".join(keep)[:40].strip("_")
    candidate, n = base, 2
    while candidate in used:
        candidate, n = f"{base}_{n}", n + 1
    used.add(candidate)
    return candidate


def _block(text: str, indent: str = "      ") -> str:
    return "\n".join(indent + line for line in text.splitlines()) or indent


def build_manifest(phase, lesson, en_items, zh_items) -> str:
    lines = [f"lesson: {lesson}", f"phase: {phase}",
             f"source: phases/{phase}/{lesson}/docs/en.md", "exercises:"]
    used = set()
    for i, en in enumerate(en_items, 1):
        zh = zh_items[i - 1] if i <= len(zh_items) else en
        kind, tier, group = classify(en)
        name = slug(en, used)
        lines += [f"  - index: {i}", f"    slug: {name}", f"    kind: {kind}",
                  f"    tier: {tier}", f"    deps_group: {group}",
                  "    en: |", _block(en), "    zh: |", _block(zh)]
        if kind == "explain":
            lines.append("    cites: TODO name the lesson section this answer draws on")
        else:
            lines.append("    verifies: TODO state the threshold this solution asserts")
    return "\n".join(lines) + "\n"


STUB = '''"""Exercise {index} — {short}.

    {en}

Reading of the exercise: TODO say how the exercise was read, and why that
reading is the defensible one.
"""

from __future__ import annotations

from harness import parity, practice

PHASE, LESSON = "{phase}", "{lesson}"


def solve():
    ref = parity.load_reference(PHASE, LESSON, "{module}")
    raise NotImplementedError("TODO")


def verify(result):
    return [practice.Check("TODO", False, "no checks written yet")]


PRACTICE_IMPL = {{"solve": solve, "verify": verify}}

if __name__ == "__main__":
    raise SystemExit(practice.selfcheck(globals()))
'''


TESTS = '''"""Every exercise in this lesson, graded by its own PRACTICE_IMPL (D13).

Generated by `scripts/scaffold_practice.py` — do not edit. The test restates no
threshold: it runs the same solve/verify pair as `demo practice run` and as
running the file directly, so the three callers cannot drift apart.
"""

from __future__ import annotations

import pathlib

import pytest

from harness import coverage, manifest, parity, practice

HERE = pathlib.Path(__file__).resolve().parent.parent
PACK = manifest.load_practice(HERE / "practice.yaml")


@pytest.mark.parametrize("exercise", PACK.code_exercises, ids=lambda e: e.stem)
def test_solution_passes_its_own_checks(exercise):
    result = practice.grade_file(HERE / exercise.filename, exercise.stem)
    assert result.status == "pass", practice.report(result)
    assert result.checks, "a solution with no checks proves nothing"


@pytest.mark.parametrize("exercise", PACK.exercises, ids=lambda e: e.stem)
def test_exercise_text_matches_upstream(exercise):
    """D12/D15: the stored spec is the upstream spec, or the build is stale."""
    upstream = coverage.exercise_block(parity.doc_text(PACK.phase, PACK.lesson, "en"))
    assert coverage.spec_hash(exercise.en) == coverage.spec_hash(upstream[exercise.index - 1])


def test_every_upstream_exercise_is_covered():
    upstream = coverage.exercise_block(parity.doc_text(PACK.phase, PACK.lesson, "en"))
    assert len(PACK.exercises) == len(upstream) == {count}
'''


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("lesson", help="e.g. 01-math-foundations/04-calculus-for-ml")
    parser.add_argument("--stubs", action="store_true", help="also write exNN_*.py stubs")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args(argv)

    phase, _, lesson = args.lesson.strip("/").rpartition("/")
    en_items = coverage.exercise_block(parity.doc_text(phase, lesson, "en"))
    zh_items = coverage.exercise_block(parity.doc_text(phase, lesson, "zh"))
    if not en_items:
        print(f"{args.lesson}: no ## Exercises block", file=sys.stderr)
        return 1
    if zh_items and len(zh_items) != len(en_items):
        print(f"warning: {len(en_items)} en items but {len(zh_items)} zh items", file=sys.stderr)

    out = DEMOS / phase / lesson / "practice"
    out.mkdir(parents=True, exist_ok=True)
    (out / "tests").mkdir(exist_ok=True)
    target = out / "practice.yaml"
    if target.exists() and not args.force:
        print(f"{target} exists; pass --force to overwrite", file=sys.stderr)
        return 1
    target.write_text(build_manifest(phase, lesson, en_items, zh_items), encoding="utf-8")
    print(f"wrote {target}  ({len(en_items)} exercises)")

    tests = out / "tests" / "test_practice.py"
    if not tests.exists() or args.force:
        tests.write_text(TESTS.format(count=len(en_items)), encoding="utf-8")
        print(f"  tests/{tests.name}")

    if args.stubs:
        from harness import manifest
        code = sorted((parity.lesson_dir(phase, lesson) / "code").glob("*.py"))
        module = code[0].stem if code else "TODO"
        for ex in manifest.load_practice(target).code_exercises:
            path = out / ex.filename
            if path.exists() and not args.force:
                continue
            path.write_text(STUB.format(index=ex.index, short=ex.slug.replace("_", " "),
                                        en=ex.en, phase=phase, lesson=lesson, module=module),
                            encoding="utf-8")
            print(f"  stub {path.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
