#!/usr/bin/env python3
"""Generate .ipynb from solutions — never hand-written (D7).

A notebook is a *view* of a solution: one markdown cell of exercise text, one
code cell of the solution, one cell that runs its checks. Nothing is authored
here that is not already in the manifest or the .py file, so a notebook can
never drift from the thing it shows.
"""

from __future__ import annotations

import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

from harness import explain, manifest, runner  # noqa: E402


def _cell(kind, source):
    base = {"cell_type": kind, "metadata": {}, "source": source.splitlines(keepends=True)}
    if kind == "code":
        base |= {"execution_count": None, "outputs": []}
    return base


def notebook(pack, directory: pathlib.Path) -> dict:
    cells = [_cell("markdown",
                   f"# {pack.phase} / {pack.lesson}\n\n"
                   f"Generated by `scripts/notebooks.py` (D7) — do not edit.\n\n"
                   f"Source: {explain.lesson_url(pack.phase, pack.lesson)}\n")]
    for ex in pack.exercises:
        cells.append(_cell("markdown",
                           f"## Exercise {ex.index} — {ex.slug}\n\n"
                           f"**en** {ex.en}\n\n**zh** {ex.zh}\n\n"
                           f"*verifies*: {ex.verifies or ex.cites}\n"))
        path = directory / ex.filename
        if ex.kind == "explain" or not path.is_file():
            continue
        cells.append(_cell("code", path.read_text(encoding="utf-8")))
        cells.append(_cell("code",
                           "for _check in PRACTICE_IMPL['verify'](PRACTICE_IMPL['solve']()):\n"
                           "    print(_check)\n"))
    return {"cells": cells, "metadata": {"kernelspec": {
        "display_name": "Python 3", "language": "python", "name": "python3"}},
        "nbformat": 4, "nbformat_minor": 5}


def main(argv=None) -> int:
    written = []
    for man_path in runner._manifests(argv[0] if argv else None):
        pack = manifest.load_practice(man_path)
        out = man_path.parent / f"{pack.lesson}.ipynb"
        out.write_text(json.dumps(notebook(pack, man_path.parent), indent=1) + "\n",
                       encoding="utf-8")
        written.append(out)
    for path in written:
        print(f"wrote {path.relative_to(pathlib.Path.cwd())}")
    return 0 if written else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
