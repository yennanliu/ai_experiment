#!/usr/bin/env python3
"""Regenerate the coverage table in README.md from the tree. (D1, risk table)

Coverage is never hand-written here. It is a diff of the reference lesson tree
against the demo tree, so the README cannot claim a lesson is done when the
directory is empty -- the failure mode the reference repo's own 295 empty
`notebook/` directories demonstrate.

    python scripts/coverage.py            # print the table
    python scripts/coverage.py --write    # rewrite the block in README.md
"""

from __future__ import annotations

import argparse
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from harness import coverage  # noqa: E402
from harness.runner import DEMOS_ROOT, REPO_ROOT  # noqa: E402

README = REPO_ROOT / "README.md"
START = "<!-- coverage:start -->"
END = "<!-- coverage:end -->"


def render(statuses) -> str:
    counts = coverage.summary(statuses)
    demos = [s.demo for s in statuses if s.demo]
    tiers: dict[str, int] = {}
    for demo in demos:
        tiers[demo.tier] = tiers.get(demo.tier, 0) + 1

    lines = [
        START,
        f"_Generated by `scripts/coverage.py` on {date.today().isoformat()}. "
        "Do not edit by hand._",
        "",
        f"**{counts[coverage.BUILT]} of {len(statuses)} lessons have a demo** "
        f"({100 * counts[coverage.BUILT] / len(statuses):.1f}%) · "
        f"{sum(1 for d in demos if d.has_parity)} carry a parity assertion · "
        + " · ".join(f"{n}×{tier}" for tier, n in sorted(tiers.items())),
        "",
        coverage.phase_table(statuses),
        "",
        f"Legend: {coverage.GLYPH[coverage.BUILT]} built · "
        f"{coverage.GLYPH[coverage.STALE]} needs revisiting · "
        f"{coverage.GLYPH[coverage.MISSING]} not started.",
    ]

    stale = [s for s in statuses if s.state == coverage.STALE]
    if stale:
        lines += ["", "**Needs revisiting**", ""]
        lines += [f"- `{s.lesson}` — {s.note}" for s in stale]
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="rewrite README.md")
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if README.md is out of date (for CI)")
    args = parser.parse_args()

    block = render(coverage.survey(DEMOS_ROOT))
    if not (args.write or args.check):
        print(block)
        return 0

    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit(f"{README} has no {START} / {END} block")
    head, _, rest = text.partition(START)
    _, _, tail = rest.partition(END)
    updated = head + block + tail

    if args.check:
        if updated != text:
            print("README.md coverage block is stale -- run "
                  "`python scripts/coverage.py --write`")
            return 1
        print("README.md coverage block is current")
        return 0

    README.write_text(updated, encoding="utf-8")
    print(f"updated {README}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
