"""Exercise 4 — top-p 0.95 keeps 227 of 256 tokens, so the two settings are not a pair.

    Implement top-k sampling (only consider the k highest-probability tokens)
    and top-p sampling (nucleus sampling: consider the smallest set of tokens
    whose cumulative probability exceeds p). Compare the output quality at
    temperature 0.8 with top-k=50 vs top-p=0.95.

Reading of the exercise: both samplers are built around `generate`'s own
temperature-and-softmax step, so the only difference between the arms is which
tokens survive truncation. "Output quality" needs a number to be a comparison,
and on a byte-level model the available one is the share of generated bytes that
are printable ASCII -- the corpus is 100% printable, so anything else is the
model failing.

**ANSWER: top-k=50 wins, 82% printable against 52%.** Averaged over five draws
of 120 bytes at temperature 0.8. Neither decodes as valid UTF-8.

**FINDING: top-p=0.95 is barely a filter here.** The nucleus holds **227 of 256
tokens** -- it removes 29. top-k=50 removes 206, a factor of seven. And it
shows: no truncation at all scores **56%** against top-p's 52%, statistically
the same thing, while top-k is 30 points above both. The exercise pairs the two
settings as comparable and one of them is doing nothing.

**MECHANISM: the distribution is nearly flat, and top-p is defined on the mass
while top-k is defined on the count.** The next-token distribution has entropy
4.941 nats against a maximum of ln(256) = 5.545 -- 89% of uniform -- and its
largest probability is 0.134. When no token is confident, 95% of the mass needs
almost every token, and the two rules stop measuring the same thing: they agree
on 50 of the 227 tokens in their union, a Jaccard of **0.220**.

**FINDING: top-k=50 is the aggressive setting, not the safe one.** The 50 tokens
it keeps carry only **0.4796** of the probability mass, so it discards more than
half of what the model believes -- and 21 of those 50 are non-printable bytes,
which is why its output is 82% printable rather than 100%. It wins this
comparison by cutting hardest, on a model flat enough that cutting hard helps.

Structure: `nucleus` and `top_k` return the surviving token indices; `sample`
runs `generate`'s loop with one of them spliced in.
"""

from __future__ import annotations

import contextlib
import io
import math
import statistics

import numpy as np

from harness import parity, practice

PHASE, LESSON = "10-llms-from-scratch", "04-pre-training-mini-gpt"
STEPS, SEED, TEMPERATURE, TOKENS = 500, 1, 0.8, 120
DRAWS = (3, 4, 5, 6, 7)
K, P = 50, 0.95
PROMPT = list(b"Machine learning is")
CORPUS = ("Machine learning is a subset of artificial intelligence. "
          "Deep learning uses neural networks with many layers. "
          "The transformer architecture relies on self-attention. "
          "Language models predict the next token in a sequence. ") * 10


def distribution(model, tokens):
    """`generate`'s own next-token step: slice, forward, temperature, softmax."""
    window = model.embedding.pos_embed.shape[0]
    logits = model.forward(np.array(tokens[-window:]).reshape(1, -1))[0, -1, :]
    logits = logits / TEMPERATURE
    probs = np.exp(logits - logits.max())
    return probs / probs.sum()


def top_k(probs, k):
    return np.argsort(probs)[::-1][:k]


def nucleus(probs, p):
    order = np.argsort(probs)[::-1]
    return order[:int(np.searchsorted(np.cumsum(probs[order]), p)) + 1]


def sample(model, rule, count, seed):
    """`generate`'s loop with `rule` deciding which tokens survive truncation."""
    rng = np.random.default_rng(seed)
    tokens = list(PROMPT)
    for _ in range(count):
        probs = distribution(model, tokens)
        keep = rule(probs)
        tokens.append(int(rng.choice(keep, p=probs[keep] / probs[keep].sum())))
    return bytes(tokens[len(PROMPT):])


def printable(body):
    return sum(1 for byte in body if 32 <= byte < 127) / len(body)


def solve():
    ref = parity.load_reference(PHASE, LESSON, "main")
    np.random.seed(SEED)
    with contextlib.redirect_stdout(io.StringIO()):
        model = ref.train_mini_gpt(CORPUS, num_steps=STEPS)
    probs = distribution(model, PROMPT)
    kept, pool = set(top_k(probs, K)), set(nucleus(probs, P))
    rules = {"top_k": lambda q: top_k(q, K), "top_p": lambda q: nucleus(q, P),
             "none": lambda q: np.arange(len(q))}
    return {
        "printable": {name: statistics.fmean(printable(sample(model, rule, TOKENS, seed))
                                             for seed in DRAWS)
                      for name, rule in rules.items()},
        "sizes": (len(kept), len(pool), len(probs)),
        "overlap": len(kept & pool) / len(kept | pool),
        "mass": float(np.sort(probs)[::-1][:K].sum()),
        "entropy": float(-(probs * np.log(probs + 1e-12)).sum()),
        "peak": float(probs.max()),
        "printable_in_k": sum(1 for i in top_k(probs, K) if 32 <= i < 127),
    }


def verify(result):
    share, (k_size, p_size, vocab) = result["printable"], result["sizes"]
    return [
        practice.Check(
            f"ANSWER: top-k={K} wins on printable output, 82% against 52%",
            share["top_k"] > share["top_p"] + 0.15,
            f"{TOKENS} generated bytes at temperature {TEMPERATURE} come back "
            f"{100 * share['top_k']:.0f}% printable ASCII under top-k={K} and "
            f"{100 * share['top_p']:.0f}% under top-p={P}. The training corpus is 100% "
            "printable, so every non-printable byte is the model failing, and neither arm "
            "decodes as valid UTF-8",
        ),
        practice.Check(
            f"FINDING: the p={P} nucleus holds {result['sizes'][1]} of {result['sizes'][2]} tokens",
            p_size > 4 * k_size and share["top_p"] - share["none"] < share["top_k"] - share["top_p"],
            f"top-p={P} removes {vocab - p_size} tokens where top-k={K} removes "
            f"{vocab - k_size} -- a factor of {(vocab - k_size) / (vocab - p_size):.0f} in how "
            f"much they cut. It shows: no truncation at all scores "
            f"{100 * share['none']:.0f}% printable against top-p's "
            f"{100 * share['top_p']:.0f}% -- statistically the same thing, with top-k "
            f"{100 * (share['top_k'] - share['none']):.0f} points above both. The exercise "
            "pairs the two settings as comparable and one of them is doing nothing",
        ),
        practice.Check(
            "MECHANISM: a nearly flat distribution makes mass and count stop agreeing",
            result["entropy"] > 0.85 * math.log(vocab) and result["overlap"] < 0.3,
            f"the next-token distribution has entropy {result['entropy']:.3f} nats against a "
            f"maximum of ln({vocab}) = {math.log(vocab):.3f} -- "
            f"{100 * result['entropy'] / math.log(vocab):.0f}% of uniform -- and its largest "
            f"probability is {result['peak']:.4f}. When no token is confident, 95% of the mass "
            f"needs nearly every token, and the two rules agree on {int(result['overlap'] * (k_size + p_size) / (1 + result['overlap']))} "
            f"of the {k_size + p_size - int(result['overlap'] * (k_size + p_size) / (1 + result['overlap']))} "
            f"in their union, a Jaccard of {result['overlap']:.3f}",
        ),
        practice.Check(
            f"FINDING: top-k={K} is the aggressive setting, discarding over half the mass",
            result["mass"] < 0.5 and result["printable_in_k"] < K,
            f"the {K} tokens it keeps carry {result['mass']:.4f} of the probability, so it "
            f"throws away more than half of what the model believes -- and only "
            f"{result['printable_in_k']} of those {K} are printable bytes, which is why its "
            f"output is {100 * share['top_k']:.0f}% printable rather than 100%. It wins by "
            "cutting hardest, on a model flat enough that cutting hard helps",
        ),
    ]


PRACTICE_IMPL = {"solve": solve, "verify": verify}

if __name__ == "__main__":
    raise SystemExit(practice.selfcheck(globals()))
