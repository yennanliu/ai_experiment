"""Exercise 2 — a real second-day task slips on the two outcomes this repo has no surface for.

    Run the comparison on a real second-day task in your codebase. Where do
    the workbench numbers slip?

Reading of the exercise: the honest version scores a task that already
shipped, with the repository's own artifacts, and reports what it finds. The
task here is the previous lesson's commit in this repository -- Lesson 40's
practice solutions -- scored on the same five outcomes the benchmark claims.

**ANSWER: the real run matches the benchmark on 3 outcomes of 5 and slips on
the two that need a surface this repository does not have.**
`tests_actually_run` and `acceptance_met` come back true against the
benchmark's true, and shipping the lesson put **8** files in the tree --
seven in its own directory plus the generated top-level README. But
`files_outside_scope` is **1**, not the claimed 0, and `handoff_quality` is
`missing` against the claimed "full packet", because no handoff packet exists
anywhere in the tree.

**FINDING: the off-scope file is generated by the repository's own tooling.**
The one path outside the lesson directory is the top-level `README.md`, which
`scripts/coverage.py` rewrites whenever a lesson lands. A contract that lists
allowed globs has no way to say "this file is written by the build", so a
mechanical byproduct is counted as scope creep -- the same finding Lesson 38's
gate produced on the same commit.

**FINDING: the reviewer scores the real task `hard_fail`, and it is right
for a reason the benchmark never models.** Running Lesson 39 over the real
artifacts gives a total of **6** with `handoff_readiness` at **0**: there is no
`agent_state.json` in this repository, so there is no `next_action` and no
closed task. The benchmark's workbench row hardcodes **9**.

**FINDING: the benchmark cannot slip, because both rows are literals.**
`run_prompt_only` and `run_workbench` return hardcoded `TaskOutcome` values and
read **0** files; `main` writes the sample app *after* the outcomes are
computed. The comparison is an assertion formatted as a measurement, which is
why running it on a real task is the exercise.

Structure: `shipped_files()` reads the real tree; `outcomes()` scores the five
against the repository's own artifacts.
"""

from __future__ import annotations

import inspect
from pathlib import Path

from harness import parity, practice

PHASE, LESSON = "14-agent-engineering", "41-workbench-for-real-repos"
TASK = "demos/phases/14-agent-engineering/40-multi-session-handoff/practice"
ROOT = next(p for p in Path(__file__).resolve().parents if (p / "demos").is_dir())


def shipped_files():
    """What shipping the previous lesson put in the tree: its practice directory,
    plus the top-level README that scripts/coverage.py regenerates with it."""
    folder = ROOT / TASK
    changed = sorted(path.relative_to(ROOT).as_posix()
                     for path in folder.rglob("*")
                     if path.is_file() and "__pycache__" not in path.parts)
    return changed + ["README.md"]


def acceptance():
    """The real acceptance run: every shipped solution graded in-process."""
    results = [practice.grade_file(path) for path in sorted((ROOT / TASK).glob("ex0*.py"))]
    return {"files": len(results), "passed": sum(r.status == "pass" for r in results),
            "checks": sum(len(r.checks) for r in results)}


def outcomes(rev, files, graded):
    """The five benchmark outcomes, measured on the real task."""
    off_scope = [path for path in files if not path.startswith(TASK)]
    packets = list(ROOT.rglob("handoff.json")) + list(ROOT.rglob("outputs/handoff"))
    report = rev.review(rev.ReviewerInputs(
        task_id="lesson-40", goal="practice solutions for the multi session handoff lesson",
        diff_summary={"touched": files}, state={},
        feedback=[{"command": "practice.grade_file", "exit_code": 0}] * graded["passed"],
        verdict={"passed": True, "findings": [{"code": "scope.off_scope"}] if off_scope else []}))
    return {"tests_actually_run": graded["files"] > 0,
            "acceptance_met": graded["passed"] == graded["files"],
            "files_outside_scope": off_scope,
            "handoff_quality": "full packet" if packets else "missing",
            "reviewer_total": report.total, "reviewer_verdict": report.verdict,
            "handoff_dimension": [d.score for d in report.dimensions
                                  if d.name == "handoff_readiness"][0]}


def solve():
    ref = parity.load_reference(PHASE, LESSON, "main")
    rev = parity.load_reference(PHASE, "39-reviewer-agent", "main")
    files = shipped_files()
    graded = acceptance()
    real = outcomes(rev, files, graded)
    claimed = ref.run_workbench()
    module = inspect.getsource(ref)
    return {
        **real, "changed": len(files), "graded": graded,
        "resolve": sum((ROOT / path).exists() for path in files),
        "claimed": {"tests": claimed.tests_actually_run, "acceptance": claimed.acceptance_met,
                    "off_scope": len(claimed.files_outside_scope),
                    "handoff": claimed.handoff_quality, "total": claimed.reviewer_total},
        "reads_files": "read_text" in inspect.getsource(ref.run_workbench)
        or "open(" in inspect.getsource(ref.run_workbench),
        "sample_written_after": module.index("write_sample()\n    po =") > module.index("def main"),
    }


def verify(result):
    claimed = result["claimed"]
    return [
        practice.Check(
            "ANSWER: the real run matches on 3 of 5 and slips on the other two",
            all([result["tests_actually_run"] is True, result["acceptance_met"] is True,
                 result["changed"] == 8, result["resolve"] == 8,
                 len(result["files_outside_scope"]) == 1,
                 result["handoff_quality"] == "missing",
                 claimed["off_scope"] == 0, claimed["handoff"] == "full packet"]),
            f"shipping the lesson put {result['changed']} files in the tree; the real run scores "
            f"tests={result['tests_actually_run']} acceptance={result['acceptance_met']} "
            f"off_scope={len(result['files_outside_scope'])} "
            f"handoff={result['handoff_quality']!r} against the benchmark's "
            f"{claimed['off_scope']} and {claimed['handoff']!r}",
        ),
        practice.Check(
            "FINDING: the off-scope file is generated by the repository's own tooling",
            result["files_outside_scope"] == ["README.md"],
            f"the one path outside the lesson directory is {result['files_outside_scope']}, "
            "rewritten by scripts/coverage.py whenever a lesson lands. A contract of allowed "
            "globs cannot say 'the build writes this', so a byproduct is counted as creep",
        ),
        practice.Check(
            "FINDING: the reviewer scores the real task hard_fail",
            all([result["reviewer_total"] == 6, result["reviewer_verdict"] == "hard_fail",
                 result["handoff_dimension"] == 0, claimed["total"] == 9]),
            f"Lesson 39 over the real artifacts totals {result['reviewer_total']}/10 and "
            f"lands on {result['reviewer_verdict']} with handoff_readiness at "
            f"{result['handoff_dimension']} -- there is no agent_state.json in this "
            f"repository -- against the benchmark's hardcoded {claimed['total']}",
        ),
        practice.Check(
            "FINDING: the benchmark cannot slip, because both rows are literals",
            all([result["reads_files"] is False, result["sample_written_after"] is True,
                 result["graded"]["checks"] == 16]),
            f"run_workbench reads no files and returns a literal, and main writes the sample "
            f"app after the outcomes are computed. The real run graded "
            f"{result['graded']['files']} files and {result['graded']['checks']} checks to "
            "get its numbers",
        ),
    ]


PRACTICE_IMPL = {"solve": solve, "verify": verify}

if __name__ == "__main__":
    raise SystemExit(practice.selfcheck(globals()))
